/**
 * Compare with RoadEng…: the road's own Mass Haul, Optimal Haul and Areas exports, loaded back,
 * show no difference; the same file with one value changed shows that difference on its own row,
 * and the row's station button moves the workspace's station there. The files are generated by
 * the page itself (Save & export), never Softree's samples.
 */
test.setTimeout(240_000)
test.use({ serviceWorkers: 'block', viewport: { width: 1512, height: 982 }, actionTimeout: 20_000 })

