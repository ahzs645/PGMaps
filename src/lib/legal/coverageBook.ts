/**
 * The coverage book: the section-by-section review (`packages/legal-rules/catalogue/section-review/`)
 * and what cites each section, compiled into one Markdown document a person can read or print
 * outside PGMaps. `scripts/legal-rules/coverage-book.ts` writes it to `docs/legal-coverage-book.md`;
 * `coverageBook.test.ts` fails when the committed book differs from the review and the packs.
 * DOM- and network-free.
 */
import type { Pack } from '../../../packages/legal-rules/src/contract'
import {
  gapsOf,
  sectionKey,
  sectionState,
  STATE_LABEL,
  type Citing,
  type CoverageReview,
  type SectionState,
} from './coverage'

export interface BookSource {
  id: string
  title: string
  url: string
  order: boolean
}

export interface BookInput {
  reviews: CoverageReview[]
  /** The citations, from `citationIndex` over the shipped packs and the ground catalogue. */
  index: Map<string, Citing[]>
  sources: BookSource[]
  /** Every shipped release; the rule index lists the newest release of each instrument. */
  packs: Pack[]
  /** Statutes first, in the order a planner meets them, then the orders. */
  priority: string[]
}

const cell = (text: string | undefined) => (text ?? '').replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim()
const SHOWN: SectionState[] = ['rule', 'screen', 'gap-high', 'gap-medium', 'gap-low']
const newer = (a: string, b: string) => a.localeCompare(b, undefined, { numeric: true }) > 0

export function coverageBook({ reviews, index, sources, packs, priority }: BookInput): string {
  const source = (id: string) => sources.find((s) => s.id === id)
  const title = (id: string) => source(id)?.title ?? id
  const label = (id: string, n: string) => (source(id)?.order ? n : `s. ${n}`)
  const rank = (id: string) => {
    const i = priority.indexOf(id)
    return i < 0 ? priority.length + (source(id)?.order ? 1 : 0) : i
  }
  const ordered = [...reviews].sort((a, b) => rank(a.source) - rank(b.source) || a.source.localeCompare(b.source))
  const state = (r: CoverageReview, n: string) =>
    sectionState(
      index.get(sectionKey(r.source, n)),
      r.sections.find((s) => s.n === n),
    )
  const counts = (r: CoverageReview) => {
    const c: Record<SectionState, number> = {
      rule: 0,
      screen: 0,
      'gap-high': 0,
      'gap-medium': 0,
      'gap-low': 0,
      outside: 0,
      unreviewed: 0,
    }
    for (const s of r.sections) c[state(r, s.n)]++
    return c
  }
  const dates = [...new Set(reviews.map((r) => r.reviewedOn))].sort()
  const out: string[] = []
  out.push('# Law coverage book', '')
  out.push(
    '<!-- Generated by `npm run legal:coverage-book` from packages/legal-rules/catalogue/section-review and the shipped packs. Do not edit by hand. -->',
    '',
  )
  out.push(
    `What the block planner's legal rules reach in each statute, regulation and Omineca order PGMaps stores, section by section. Read on ${dates.join(', ')}. This is a machine-assisted reading, not a legal review: whether a rule or a map screen cites a section is a fact about the packs, and what each section bears on and what is left is a reading of its text. The contract is [Block planning and Prince George forest patch scenarios](forestry-patch-scenarios.md), **The law behind a finding**; what to build next is in [Block planner: next steps](forestry-block-planning-next-steps.md).`,
    '',
  )
  out.push('**How to read a row.**', '')
  out.push(
    `- *${STATE_LABEL.rule}*: a pack rule cites the section, so a block review asks about it. The note says what the rule still leaves to the reviewer.`,
    `- *${STATE_LABEL.screen}*: only a map screen of *On this ground* cites it.`,
    '- *Gap: high*, *medium* or *low*: no rule cites it and the reading found something a block review should test, by priority.',
    `- *${STATE_LABEL.outside}*: administration, tenure, enforcement, definitions or repealed text. These are listed by number only.`,
    '',
  )

  out.push('## Summary', '')
  out.push('| Source | Sections | A rule | A screen | Gap: high | Gap: medium | Gap: low | Not about a block |')
  out.push('| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |')
  for (const r of ordered) {
    const c = counts(r)
    out.push(
      `| [${cell(title(r.source))}](#${anchor(title(r.source))}) | ${r.sections.length} | ${c.rule} | ${c.screen} | ${c['gap-high']} | ${c['gap-medium']} | ${c['gap-low']} | ${c.outside + c.unreviewed} |`,
    )
  }
  out.push('')

  out.push('## Open gaps', '')
  out.push(
    'High and medium gaps no rule cites, highest first. A section a rule cites can still carry a note on what is left; those are in each source below.',
    '',
  )
  const open = gapsOf(ordered).filter(
    ({ source: s, entry }) =>
      entry.gapPriority !== 'low' && state(ordered.find((r) => r.source === s)!, entry.n) !== 'rule',
  )
  if (!open.length) out.push('None.', '')
  else {
    out.push('| Priority | Source | Section | What a rule would need |', '| --- | --- | --- | --- |')
    for (const { source: s, entry } of open)
      out.push(
        `| ${entry.gapPriority} | ${cell(title(s))} | ${cell(label(s, entry.n))} | ${cell(entry.gapNote ?? entry.bearsOn)} |`,
      )
    out.push('')
  }

  out.push('## Rules by instrument', '')
  const latest = new Map<string, Pack>()
  for (const p of packs) if (!latest.has(p.id) || newer(p.version, latest.get(p.id)!.version)) latest.set(p.id, p)
  for (const p of [...latest.values()].sort((a, b) => a.id.localeCompare(b.id))) {
    out.push(`### ${cell(p.title)} (\`${p.id}\` ${p.version})`, '')
    out.push('| Rule | Cites | Source |', '| --- | --- | --- |')
    for (const r of p.rules) {
      const s = p.sources.find((x) => x.id === r.source)
      out.push(`| ${cell(r.title)} (\`${r.id}\`) | ${cell(r.provision)} | ${cell(s?.title)} |`)
    }
    out.push('')
  }

  out.push('## Source by source', '')
  for (const r of ordered) {
    const src = source(r.source)
    out.push(`### ${cell(title(r.source))}`, '')
    out.push(
      `\`${r.source}\` · [${src?.order ? 'Signed order' : 'BC Laws'}](${src?.url ?? ''}) · read ${r.reviewedOn}`,
      '',
    )
    const shown = r.sections.filter((s) => SHOWN.includes(state(r, s.n)))
    if (shown.length) {
      out.push('| Section | Status | Bears on | Cited by | What is left |', '| --- | --- | --- | --- | --- |')
      for (const s of shown) {
        const st = state(r, s.n)
        const cited = [...new Set((index.get(sectionKey(r.source, s.n)) ?? []).map((c) => c.id))]
        out.push(
          `| ${cell(label(r.source, s.n))} | ${STATE_LABEL[st]} | ${cell(s.bearsOn)} | ${cited.map((c) => `\`${c}\``).join(', ')} | ${cell(s.gapNote)} |`,
        )
      }
      out.push('')
    }
    const rest = r.sections.filter((s) => !SHOWN.includes(state(r, s.n))).map((s) => s.n)
    if (rest.length) out.push(`Not about a block: ${rest.join(', ')}.`, '')
  }
  return out.join('\n')
}

/** GitHub's heading anchor: lower case, punctuation dropped, spaces as hyphens. */
export function anchor(heading: string) {
  return heading
    .toLowerCase()
    .replace(/[^\p{L}\p{N}\s-]/gu, '')
    .trim()
    .replace(/\s/g, '-')
}
