import { Badge } from '@/components/ui/badge'
import { InlineAlert } from '@/components/ui/map-panels'
import { ExternalLink } from '@/components/ui/text-button'
import { CASTOR_LIMITS } from '@/features/forestry-castor/validation'
import type { CastorProject, CastorResult } from '@/features/forestry-castor/types'
import { number, Section } from './common'

export function MethodsPanel({ project, result }: { project: CastorProject | null; result: CastorResult | null }) {
  return (
    <div className="space-y-5">
      <InlineAlert title="A browser adaptation of forestryCastor">
        This workbench explores management scenarios from supplied forest data. It adapts the source model's workflow
        and records its changes; it is not a certified timber-supply analysis or a claim of complete numerical
        equivalence with the original R/SpaDES system.
      </InlineAlert>
      <div className="grid gap-5 lg:grid-cols-2">
        <Section title="Source and scenario provenance">
          <div className="space-y-3 text-sm leading-6">
            <p>
              <ExternalLink href="https://github.com/bcgov/forestryCastor">forestryCastor</ExternalLink> and its
              accompanying growing-stock module are published by the Province of British Columbia under Apache 2.0. The
              browser model keeps source attribution and an explicit method version in exported results.
            </p>
            <p>
              <ExternalLink href="https://github.com/bcgov/dataCastor">dataCastor</ExternalLink> supplies the source
              example database. That tutorial dataset is separate from the synthetic demonstration generated by this
              page.
            </p>
            {project && (
              <div className="rounded-md border bg-muted/30 p-3">
                <p className="font-medium">{project.provenance.source}</p>
                {project.provenance.synthetic && (
                  <Badge tone="warning" size="sm">
                    Synthetic inputs
                  </Badge>
                )}
                {typeof project.provenance.url === 'string' && /^https?:\/\//i.test(project.provenance.url) && (
                  <p className="break-words">
                    <ExternalLink href={project.provenance.url}>Input source</ExternalLink>
                  </p>
                )}
                {typeof project.provenance.revision === 'string' && (
                  <p className="break-all text-xs">Revision: {project.provenance.revision}</p>
                )}
                <ul className="mt-2 list-disc space-y-2 pl-5 text-xs leading-5">
                  {project.provenance.notes.map((note, index) => (
                    <li key={index}>{note}</li>
                  ))}
                </ul>
              </div>
            )}
          </div>
        </Section>
        <Section title="What a run includes">
          <ul className="list-disc space-y-3 pl-5 text-sm leading-6">
            <li>Yield-curve growth, volume and height updates, ECA and supplied stand attributes.</li>
            <li>
              Period harvest targets and priorities, live and salvage queues, pixel or block units, and explicit
              scheduled harvests.
            </li>
            <li>
              No-harvest zones, attribute/cover conditions, ECA and disturbance-distance constraints, adjacency and a
              growing-stock retention floor.
            </li>
            <li>
              Partial-cut treatments and their specified age, yield-curve or next-treatment transitions. These are
              explicit browser extensions to incomplete upstream branches.
            </li>
            <li>
              Reports for harvest flows, standing timber, management constraints, salvage balances, harvested pixels and
              blocks, and candidate landings.
            </li>
            <li>
              Per-period spatial snapshots, GeoJSON and GeoTIFF exports, a recoverable scenario file, and a report
              bundle.
            </li>
          </ul>
        </Section>
      </div>
      <Section title="Reading the outputs">
        <div className="grid gap-5 text-sm leading-6 md:grid-cols-2">
          <div>
            <h3 className="mb-1 font-medium">Volume and area</h3>
            <p className="text-muted-foreground">
              Live and salvage volumes are densities in m³/ha multiplied by the pixel's timber-harvesting land-base
              hectares. Landscape area and harvesting area remain separate. A repeatedly treated pixel contributes to
              multiple period treatment areas.
            </p>
          </div>
          <div>
            <h3 className="mb-1 font-medium">Targets and shortfall</h3>
            <p className="text-muted-foreground">
              Targets are period totals. A target can remain unmet when eligible units are exhausted or constraints
              bind. Annualized report values divide period totals by years per period. A zero shortfall does not
              establish ecological or operational feasibility.
            </p>
          </div>
          <div>
            <h3 className="mb-1 font-medium">Constraint attainment</h3>
            <p className="text-muted-foreground">
              The management report retains its zone, denominator, protected area and measured percentage, before and
              after harvest. Existing conditions may fail a target before any action. The accumulated constraint raster
              counts the time a pixel was unavailable under the model's constraints.
            </p>
          </div>
          <div>
            <h3 className="mb-1 font-medium">Maps and landings</h3>
            <p className="text-muted-foreground">
              No-data grid cells remain no-data. Harvest-year cells record the most recent harvest by the selected
              period; the pixel report retains every event. Landings use supplied locations where available and identify
              generated candidates. Road routing and field suitability require further analysis.
            </p>
          </div>
        </div>
      </Section>
      <Section title="Assumptions and limits">
        <ul className="list-disc space-y-3 pl-5 text-sm leading-6">
          <li>
            The browser adaptation makes its treatment of yield endpoints, area weighting, stock retention, queue limits
            and partial-cut volume explicit. Use the documented source comparisons before interpreting results as
            reproductions of an upstream R run.
          </li>
          <li>
            Yield uncertainty is a sensitivity analysis driven by the supplied coefficient of variation and random seed.
            The upstream README advertises gamma calibration, but the module does not implement it or supply calibration
            data. These sensitivity intervals are not calibrated Castor prediction intervals.
          </li>
          <li>
            Distance updating measures proximity to new harvest while preserving the supplied initial distance. It does
            not reproduce disturbanceCastor road effects or recovery.
          </li>
          <li>
            Provincial raster preparation, private database access and generation of locally calibrated growth curves
            remain input preparation tasks. This page reads bounded local datasets; it does not download a province-wide
            forest database.
          </li>
          <li>
            Runs are bounded to {number(CASTOR_LIMITS.pixels)} pixels, {number(CASTOR_LIMITS.periods)} periods and{' '}
            {number(CASTOR_LIMITS.pixelPeriods)} pixel-period combinations. Other complexity checks apply to
            constraints, grids and uncertainty. Split a larger study area or reduce the horizon before importing.
          </li>
        </ul>
        {result && (
          <div className="mt-5 space-y-4">
            <p className="text-xs text-muted-foreground">
              Model version: <code>{result.modelVersion}</code>
            </p>
            {!!result.warnings.length && (
              <InlineAlert tone="warning" title="Run diagnostics">
                <ul className="list-disc space-y-2 pl-5">
                  {result.warnings.map((warning, index) => (
                    <li key={index}>{warning}</li>
                  ))}
                </ul>
              </InlineAlert>
            )}
            {!!result.assumptions.length && (
              <details className="rounded-md border p-3" open>
                <summary className="cursor-pointer text-sm font-medium">Assumptions recorded with this run</summary>
                <ul className="mt-3 list-disc space-y-2 pl-5 text-xs leading-5">
                  {result.assumptions.map((assumption, index) => (
                    <li key={index}>{assumption}</li>
                  ))}
                </ul>
              </details>
            )}
          </div>
        )}
        <div className="mt-4 flex flex-wrap gap-x-5 gap-y-2 text-sm">
          <ExternalLink href="https://github.com/ahzs645/PGMaps/blob/63cb0f7e1570d27292f0ae048adff4061c340f0d/docs/forestry-castor.md">
            Model and input documentation
          </ExternalLink>
          <ExternalLink href="https://github.com/bcgov/forestryCastor/blob/e2a580eb1fcc634780bb3599da7265a1e871484f/LICENSE">
            Upstream licence
          </ExternalLink>
        </div>
      </Section>
    </div>
  )
}
