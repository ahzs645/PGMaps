import { describe, expect, it } from 'vitest'
import { createBrowserExportPlan } from './browserExport'
import {
  GEOREFERENCE_RECOVERY_SCHEMA,
  parseProject,
  serializeProject,
  type GeoreferenceProject,
  type Point,
} from './model'
import { fitTransformation } from './transforms'

function recovered(): GeoreferenceProject {
  return {
    schema: GEOREFERENCE_RECOVERY_SCHEMA,
    pixelConvention: 'pixel-centres-x-right-y-down',
    fitCrs: 'EPSG:3857',
    transform: 'affine',
    source: {
      id: 'synthetic-recovery',
      url: 'https://example.test/source.png',
      sha256: 'a'.repeat(64),
      width: 100,
      height: 80,
      frame: { kind: 'derived-image', description: 'Synthetic lossless masked original pixel grid.' },
    },
    points: [],
    recoveredPlacement: {
      crs: 'EPSG:3005',
      matrix: [
        [1, 0, 1000000],
        [0, -1, 1000000],
      ],
      active: true,
      method: 'archived-constrained-affine',
      summary: 'Preserved matrix; no paired control evidence is invented.',
      recoveredAt: '2026-11-08',
      evidence: [{ label: 'Synthetic legacy record', sha256: 'b'.repeat(64) }],
    },
  }
}

describe('exact recovered native placements', () => {
  it('matches independently computed GDAL/PROJ coordinates without requiring fabricated controls', () => {
    const fit = fitTransformation(recovered())
    // Rasterio/GDAL EPSG:3005 → 4326 values; these are not generated by the browser implementation.
    const cases: [Point, Point][] = [
      [
        [0, 0],
        [-126, 54.003488926162824],
      ],
      [
        [27.625, 45.75],
        [-125.99957755537274, 54.00307900714667],
      ],
      [
        [99, 73.5],
        [-125.99848608986801, 54.00283035941997],
      ],
    ]
    for (const [pixel, expected] of cases) {
      const coordinate = fit.forward(pixel)
      expect(coordinate[0]).toBeCloseTo(expected[0], 8)
      expect(coordinate[1]).toBeCloseTo(expected[1], 8)
      const inverse = fit.inverse(expected)!
      expect(inverse[0]).toBeCloseTo(pixel[0], 3)
      expect(inverse[1]).toBeCloseTo(pixel[1], 3)
    }
    expect(fit.matrix3857).toBeUndefined()
    expect(fit.nativeMatrix?.crs).toBe('EPSG:3005')
    expect(fit.stats.control.count).toBe(0)
    expect(fit.diagnostics.minimumControls).toBe(0)
    expect(fit.recovered).toBe(true)
  })

  it('keeps the archived matrix fixed while reporting actual evidence and its residuals', () => {
    const input = recovered()
    input.points = [
      {
        id: 'inherited-grid-A',
        pixel: [30, 20],
        coordinate: [-126, 54],
        enabled: true,
        role: 'control',
        provenance: {
          kind: 'inherited-grid',
          description: 'A printed-grid correspondence inherited from a separate parent frame.',
        },
      },
    ]
    const fit = fitTransformation(input)
    expect(fit.stats.control.count).toBe(1)
    expect(fit.residuals[0].usedInFit).toBe(false)
    expect(fit.residuals[0].groundMetres).toBeGreaterThan(100)
    expect(fit.forward([30, 20])).toEqual(fitTransformation(recovered()).forward([30, 20]))
    const parsed = parseProject(serializeProject(input))
    expect(parsed.recoveredPlacement).toEqual(input.recoveredPlacement)
    expect(parsed.points[0].provenance).toEqual(input.points[0].provenance)
    input.recoveredPlacement!.active = false
    expect(() => fitTransformation(input)).toThrow(/at least 3/)
  })

  it('requires an explicit v2 model, invertible matrix, and verified source identity', () => {
    const input = recovered()
    expect(() => parseProject({ ...input, schema: 'pgmaps-georeference-v1' })).toThrow(/v2/)
    expect(() => parseProject({ ...input, recoveredPlacement: undefined })).toThrow(/Recovered/)
    expect(() => parseProject({ ...input, source: { ...input.source, sha256: null } })).toThrow(/SHA-256/)
    expect(() =>
      parseProject({
        ...input,
        recoveredPlacement: {
          ...input.recoveredPlacement,
          matrix: [
            [1, 2, 0],
            [2, 4, 0],
          ],
        },
      }),
    ).toThrow(/invertible/)
    expect(() =>
      parseProject({ ...input, recoveredPlacement: { ...input.recoveredPlacement, crs: 'EPSG:3857' } }),
    ).toThrow(/3005/)
  })

  it('exports the archived matrix in its native CRS before reprojection, with one half-pixel conversion', () => {
    const input = recovered()
    input.recoveredPlacement!.matrix = [
      [2, 0.5, 1000000],
      [0.25, -3, 1000000],
    ]
    input.transform = 'thin-plate-spline' // The chosen future fit must not override the active recovered model.
    const plan = createBrowserExportPlan(input)
    expect(plan.translateArgs.slice(0, 4)).toEqual(['-of', 'VRT', '-a_srs', 'EPSG:3005'])
    expect(plan.gcps).toEqual([
      { pixel: [0.5, 0.5], projected: [1000000, 1000000] },
      { pixel: [99.5, 0.5], projected: [1000198, 1000024.75] },
      { pixel: [0.5, 79.5], projected: [1000039.5, 999763] },
    ])
    expect(plan.warpArgs[plan.warpArgs.indexOf('-s_srs') + 1]).toBe('EPSG:3005')
    expect(plan.warpArgs[plan.warpArgs.indexOf('-t_srs') + 1]).toBe('EPSG:3857')
    expect(plan.warpArgs).toContain('SRC_METHOD=GCP_POLYNOMIAL')
    expect(plan.warpArgs).not.toContain('-tps')
  })
})
